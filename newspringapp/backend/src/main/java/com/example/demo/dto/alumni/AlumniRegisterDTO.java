package com.example.demo.dto.alumni;

public class AlumniRegisterDTO {
    private String uname;
    private String udepartment;
    private String ubatch;
    private String uemail;
    private String upassword;

    // Getters and Setters
    public String getUname() { return uname; }
    public void setUname(String uname) { this.uname = uname; }

    public String getUdepartment() { return udepartment; }
    public void setUdepartment(String udepartment) { this.udepartment = udepartment; }

    public String getUbatch() { return ubatch; }
    public void setUbatch(String ubatch) { this.ubatch = ubatch; }

    public String getUemail() { return uemail; }
    public void setUemail(String uemail) { this.uemail = uemail; }

    public String getUpassword() { return upassword; }
    public void setUpassword(String upassword) { this.upassword = upassword; }
}

